# Cell 2: setup + vectorised helper
# =============================================================================
c_setup = make_code([
    "# ============================================================",
    "# Section 14  Setup: constants and vectorised Hamiltonian builder",
    "# ============================================================",
    "import time as _time14",
    "from scipy.sparse import coo_matrix as _coo14",
    "",
    "SOLVER_TRACK_COUNTS = [2, 4, 6, 8, 10, 15, 20, 30, 40, 50, 60, 75, 100]",
    "N_REPEATS_SOLVER    = 5",
    "SOLVER_THRESHOLD    = DELTA / (DELTA + GAMMA)   # 0.25 = delta/(delta+gamma)",
    "DROP_RATE_SOLVER    = 0.01",
    "",
    'print(f"Track counts  : {SOLVER_TRACK_COUNTS}")',
    'print(f"Repeats/point : {N_REPEATS_SOLVER}")',
    'print(f"Threshold     : {SOLVER_THRESHOLD:.4f}  (= delta/(delta+gamma))")',
    "",
    "",
    "def _build_ham_vectorized(ham):",
    "    # Vectorised off-diagonal construction for SimpleHamiltonianFast.",
    "    # Replaces the O(n_seg^4) Python double-loop in construct_hamiltonian with",
    "    # an O(n_seg^3) numpy approach: segments are grouped by shared middle hit,",
    "    # then kink angles are batch-computed with numpy dot products.",
    "    # Requires ham.construct_segments(event) to have been called first.",
    "    # Sets ham.A and ham.b in-place; returns nothing.",
    "    n    = ham.n_segments",
    "    vecs = ham._segment_vectors                  # (n, 3)  float64",
    "    hits = np.array(ham._segment_to_hit_ids)     # (n, 2)  int",
    "    bds  = ham._group_boundaries                 # len = n_groups + 1",
    "",
    "    diag = -(ham.delta + ham.gamma)",
    "    rows = list(range(n))",
    "    cols = list(range(n))",
    "    vals = [diag] * n",
    "",
    "    for gi in range(len(ham.segments_grouped) - 1):",
    "        i0, i1 = bds[gi],     bds[gi + 1]",
    "        j0, j1 = bds[gi + 1], bds[gi + 2]",
    "",
    "        end_hits   = hits[i0:i1, 1]   # end   hits of left-group segs",
    "        start_hits = hits[j0:j1, 0]   # start hits of right-group segs",
    "",
    "        # vectorised shared-middle-hit detection",
    "        unique_mid = np.intersect1d(end_hits, start_hits)",
    "        if unique_mid.size == 0:",
    "            continue",
    "",
    "        ii_parts, jj_parts = [], []",
    "        for h in unique_mid:",
    "            li = np.where(end_hits   == h)[0]   # local left  indices",
    "            rj = np.where(start_hits == h)[0]   # local right indices",
    "            ii_parts.append(np.repeat(li, len(rj)))",
    "            jj_parts.append(np.tile  (rj, len(li)))",
    "",
    "        ii = np.concatenate(ii_parts)   # local indices into left  group",
    "        jj = np.concatenate(jj_parts)   # local indices into right group",
    "",
    "        # batch kink-angle computation",
    "        vi    = vecs[i0 + ii]   # (k, 3)",
    "        vj    = vecs[j0 + jj]   # (k, 3)",
    "        cos_a = np.clip((vi * vj).sum(axis=1), -1.0, 1.0)",
    "        ang   = np.arccos(cos_a)",
    "        ok    = ang < ham.epsilon",
    "",
    "        if not ok.any():",
    "            continue",
    "",
    "        sid_i = (i0 + ii[ok]).tolist()",
    "        sid_j = (j0 + jj[ok]).tolist()",
    "        rows.extend(sid_i + sid_j)",
    "        cols.extend(sid_j + sid_i)",
    "        vals.extend([1.0] * (len(sid_i) + len(sid_j)))",
    "",
    "    A      = _coo14((vals, (rows, cols)), shape=(n, n)).tocsc()",
    "    ham.A  = -A",
    "    ham.b  = np.ones(n) * ham.delta",
    "",
    "",
    "def _solver_metrics(event):",
    "    # Run classical solver on one event; return segment truth/active counts.",
    "    ham = SimpleHamiltonianFast(",
    "        epsilon=FIXED_EPSILON, gamma=GAMMA, delta=DELTA)",
    "    ham.construct_segments(event)",
    "    _build_ham_vectorized(ham)",
    "    sol    = ham.solve_classicaly()",
    "    active = sol > SOLVER_THRESHOLD",
    "",
    "    truth = np.array(",
    "        [s.hit_start.track_id == s.hit_end.track_id",
    "         and s.hit_start.track_id >= 0",
    "         for s in ham.segments])",
    "",
    "    n_true_all     = int(truth.sum())",
    "    n_false_all    = ham.n_segments - n_true_all",
    "    n_true_active  = int((active & truth).sum())",
    "    n_active       = int(active.sum())",
    "    n_false_active = n_active - n_true_active",
    "",
    "    return {",
    "        'n_true_all':     n_true_all,",
    "        'n_false_all':    n_false_all,",
    "        'n_true_active':  n_true_active,",
    "        'n_false_active': n_false_active,",
    "        'n_active':       n_active,",
    "    }",
    "",
    "",
    "def _agg_solver(raw):",
    "    # Aggregate per-repeat raw dicts into plot-ready arrays.",
    "    tc        = np.array(SOLVER_TRACK_COUNTS, dtype=float)",
    "    se_m, se_e          = [], []",
    "    fr_m, fr_e          = [], []",
    "    ntm, ntse           = [], []",
    "    nfm, nfse           = [], []",
    "    tam, tase           = [], []",
    "    fam, fase           = [], []",
    "",
    "    for k in SOLVER_TRACK_COUNTS:",
    "        recs = raw[k]",
    "        nr   = len(recs)",
    "        eff  = np.array([r['n_true_active'] / max(r['n_true_all'],  1) * 100",
    "                         for r in recs])",
    "        na_a = np.array([r['n_active'] for r in recs], dtype=float)",
    "        fr   = np.array([r['n_false_active'] / max(na, 1) * 100",
    "                         for r, na in zip(recs, na_a)])",
    "        def sem14(a): return a.std(ddof=1) / np.sqrt(nr) if nr > 1 else 0.",
    "        se_m.append(eff.mean());  se_e.append(sem14(eff))",
    "        fr_m.append(fr.mean());   fr_e.append(sem14(fr))",
    "        _nt = np.array([r['n_true_all']     for r in recs])",
    "        _nf = np.array([r['n_false_all']    for r in recs])",
    "        _ta = np.array([r['n_true_active']  for r in recs])",
    "        _fa = np.array([r['n_false_active'] for r in recs])",
    "        ntm.append(_nt.mean());  ntse.append(sem14(_nt))",
    "        nfm.append(_nf.mean());  nfse.append(sem14(_nf))",
    "        tam.append(_ta.mean());  tase.append(sem14(_ta))",
    "        fam.append(_fa.mean());  fase.append(sem14(_fa))",
    "",
    "    return dict(tc=tc,",
    "                se_m=np.array(se_m),  se_e=np.array(se_e),",
    "                fr_m=np.array(fr_m),  fr_e=np.array(fr_e),",
    "                ntm=np.array(ntm),    ntse=np.array(ntse),",
    "                nfm=np.array(nfm),    nfse=np.array(nfse),",
    "                tam=np.array(tam),    tase=np.array(tase),",
    "                fam=np.array(fam),    fase=np.array(fase))",
    "",
    "",
    "# colour palette (matches Section 13d)",
    "_c14_eff   = '#1b7837'",
    "_c14_fr    = '#c51b7d'",
    "_c14_true  = '#2166ac'",
    "_c14_false = '#d6604d'",
    "_c14_base  = '#1f78b4'",
    "_c14_drop  = '#e31a1c'",
    "",
    'print("Section 14 setup complete.")',
])


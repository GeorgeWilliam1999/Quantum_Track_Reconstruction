    "| iv) | Active segment pairs | $N_{\\rm true\\,active}$ and $N_{\\rm false\\,active}$ vs $N_{\\rm tracks}$ |\n"
    "\n"
    "**Fixed parameters**: gamma=3, delta=1.0, threshold=0.25,\n"
    "epsilon = 2 mrad, sigma_res=5 um, sigma_scatt=0.1 mrad.\n"

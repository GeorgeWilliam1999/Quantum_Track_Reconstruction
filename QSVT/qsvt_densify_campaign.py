"""qsvt_densify_campaign.py — densify the paper figures' data, by the standard
store protocols (direct row construction as in qsvt_robustness_campaign.py;
sol_key dedup; solutions.csv/.bak; per-study metrics merge; phases SERIALIZED).

Phase A (headline curves, Verify_new_results):
  - NEW T points {30, 75, 150, 300, 550} filling the log-T axis,
    gamma in {1,2,3} x drop in {0, 0.01}, reps: 10 (T<=300) / 5 (T=550),
    solvers: classical + qsvt (both ~seconds per solve).
  - TOP-UP existing gamma=3 points (both drops): qsvt reps -> 10 at
    T in {10,20,50,100,200,400} and -> 5 at {700,1000}; classical partners
    solved wherever missing.

Phase C (noise curves, QSVT_robustness):
  - NEW configs sigma_scatt {2e-4,4e-4,6e-4}, sigma_res {0.0025,0.0075},
    drop {0.005, 0.03}; x T {100,400}; reps 0-4. Existing 9 configs topped
    up from 3 -> 5 reps. classical + qsvt.

Phase B (1BQF top-up, the expensive tail — runs LAST):
  - gamma=3, both drops: T {10,20,30,50,75} -> 10 reps; T {100,150,200} -> 5.
    (T>=300 untouched: statevector cost explodes, 261 s @400 ... 6.6 h @700.)

NOTE: solutions.csv is regenerated by qp.build_manifest from specs — a rebuild
drops these rows (npz survive; re-run this script to re-register).
Usage: Q_env python qsvt_densify_campaign.py [--dry-run] [--phases ACB]
"""
